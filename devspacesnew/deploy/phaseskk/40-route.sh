#!/usr/bin/env bash
# Phase 40 — ROUTE. Give people a way to reach the portal.
#
# WHAT   Depending on EXPOSE in env.sh:
#          port-forward  nothing is created; prints the kubectl command (default, zero risk)
#          ingress       a Kubernetes Ingress for PORTAL_HOST on INGRESS_CLASS (nginx, traefik, alb, …)
#          istio         a Gateway + VirtualService on the Istio ingress gateway that already exists
#        plus, for both public modes, a NetworkPolicy letting the controller/gateway namespace
#        reach the portal pods (the chart only lets its own auth proxy in). With AUTH=dev the
#        route is refused unless ALLOW_CIDRS says who may use it; the allow-list becomes an
#        nginx annotation or an Istio AuthorizationPolicy.
# WHY    The route is NOT part of the Helm release so you can switch it (nginx today, Istio
#        tomorrow), change hosts or TLS, or remove it, without an upgrade of the platform.
# NEEDS  30 (the Service workspace-portal must exist), detected.env (INGRESS_CLASS_DETECTED,
#        GW_NS/GW_SELECTOR/GW_IP), DNS for PORTAL_HOST pointing at the controller/gateway IP.
# MAKES  route.yaml (everything applied, to read or keep in git) + the objects in it.
# RE-RUN safe. `./40-route.sh --remove` deletes exactly what route.yaml contains.
#   ./40-route.sh [--dry-run] [--show] [--remove]
. "$(dirname "$0")/_lib.sh" "$@"; need_detect
SHOW=0; REMOVE=0; for _a in "$@"; do case "$_a" in --show) SHOW=1;; --remove) REMOVE=1;; esac; done
OUT="$PH_DIR/route.yaml"; SCHEME=$(scheme)

if [ "$REMOVE" = 1 ]; then step "Removing the route"; [ -f "$OUT" ] && run k delete -f "$OUT" --ignore-not-found && rm -f "$OUT" && ok "gone" || skip "no route.yaml"; exit 0; fi

if [ "$EXPOSE" = port-forward ]; then
  step "EXPOSE=port-forward — nothing to create"
  cat <<EOT
  Each person who needs the portal runs:
    kubectl $KCTX_FLAG -n $SYSTEM_NS port-forward svc/workspace-portal 8080:80
  and opens http://localhost:8080  (wsctl login --portal http://localhost:8080$([ "$AUTH" = dev ] && echo " --dev"))
  This needs kubectl access to $SYSTEM_NS, which is why it is only right for a trial.
  To go public later: set EXPOSE=ingress or istio in env.sh and run this phase again.
Next:  ./50-developers.sh
EOT
  exit 0
fi

[ -n "$PORTAL_HOST" ] || fail "PORTAL_HOST is empty — the DNS name people will type"
if [ "$AUTH" = dev ] && [ -z "$ALLOW_CIDRS" ]; then
  fail "AUTH=dev has no login: publishing it would let the whole internet act as $DEV_USER. Set ALLOW_CIDRS=\"<your ip>/32\" (curl -s https://ifconfig.me) or switch to AUTH=oidc."
fi
cidr_list=$(printf '%s' "$ALLOW_CIDRS" | tr ',' '\n' | sed 's/^ *//;s/ *$//' | grep -v '^$' | paste -sd, -)
cidr_json=$(printf '%s' "$cidr_list" | tr ',' '\n' | sed 's/.*/"&"/' | paste -sd, -)

render_ingress() {
  cls=${INGRESS_CLASS:-$INGRESS_CLASS_DETECTED}; [ -n "$cls" ] || [ "$DRY_RUN" = 1 ] || fail "no IngressClass found; set INGRESS_CLASS in env.sh"
  ctrl_ns=$(kq get pods -A -l "app.kubernetes.io/name in (ingress-nginx, traefik)" -o jsonpath='{.items[0].metadata.namespace}'); ctrl_ns=${ctrl_ns:-ingress-nginx}
  cat <<EOT
# generated by deploy/phases/40-route.sh (EXPOSE=ingress, class ${cls:-<default>})
# 1. The Ingress: "$PORTAL_HOST → Service workspace-portal:80". The tunnel path is a long-lived
#    WebSocket, so the nginx timeouts are raised; other controllers ignore annotations they don't know.
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: devspaces
  namespace: $SYSTEM_NS
  labels: { app.kubernetes.io/part-of: devspaces }
  annotations:
    nginx.ingress.kubernetes.io/proxy-read-timeout: "3600"
    nginx.ingress.kubernetes.io/proxy-send-timeout: "3600"
    nginx.ingress.kubernetes.io/proxy-body-size: "20m"
$([ -n "$cidr_list" ] && printf '    nginx.ingress.kubernetes.io/whitelist-source-range: "%s"   # ALLOW_CIDRS (AUTH=dev door lock)\n' "$cidr_list")
$([ -n "$TLS_SECRET" ] && printf '    nginx.ingress.kubernetes.io/ssl-redirect: "true"\n' || printf '    nginx.ingress.kubernetes.io/ssl-redirect: "false"\n')
spec:
$([ -n "$cls" ] && printf '  ingressClassName: %s\n' "$cls")
$([ -n "$TLS_SECRET" ] && printf '  tls: [{ hosts: ["%s"], secretName: %s }]\n' "$PORTAL_HOST" "$TLS_SECRET")
  rules:
    - host: $PORTAL_HOST
      http:
        paths:
          - path: /
            pathType: Prefix
            backend: { service: { name: workspace-portal, port: { number: 80 } } }
---
# 2. Let the ingress controller's namespace reach the portal pods (the chart's own policy only
#    admits its auth proxy). Namespace detected: $ctrl_ns
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: workspace-portal-from-route
  namespace: $SYSTEM_NS
  labels: { app.kubernetes.io/part-of: devspaces }
spec:
  podSelector: { matchLabels: { app.kubernetes.io/name: workspace-portal } }
  policyTypes: [Ingress]
  ingress:
    - from: [{ namespaceSelector: { matchLabels: { kubernetes.io/metadata.name: $ctrl_ns } } }]
      ports: [{ port: 8080, protocol: TCP }]
EOT
}

render_istio() {
  [ -n "$GW_SELECTOR" ] || [ "$DRY_RUN" = 1 ] || fail "no Istio ingress gateway found by 00-check.sh"
  gw_ns=${GW_NS:-istio-system}; sel=${GW_SELECTOR:-istio: ingressgateway}
  cat <<EOT
# generated by deploy/phases/40-route.sh (EXPOSE=istio, gateway $gw_ns / $sel)
# 1. Gateway: "on the gateway pods that already exist (selector), listen for this host".
apiVersion: networking.istio.io/v1
kind: Gateway
metadata:
  name: devspaces
  namespace: $SYSTEM_NS
  labels: { app.kubernetes.io/part-of: devspaces }
spec:
  selector: { $sel }
  servers:
    - port: { number: 80, name: http, protocol: HTTP }
      hosts: ["$PORTAL_HOST"]
$([ -n "$TLS_SECRET" ] && cat <<EOT2
      tls: { httpsRedirect: true }
    - port: { number: 443, name: https, protocol: HTTPS }
      hosts: ["$PORTAL_HOST"]
      tls: { mode: SIMPLE, credentialName: $TLS_SECRET }      # Secret in namespace $gw_ns
EOT2
)
---
# 2. VirtualService: "requests for this host go to the portal Service". The tunnel path is a
#    WebSocket that stays open for hours: no timeout, no retries.
apiVersion: networking.istio.io/v1
kind: VirtualService
metadata:
  name: devspaces
  namespace: $SYSTEM_NS
  labels: { app.kubernetes.io/part-of: devspaces }
spec:
  hosts: ["$PORTAL_HOST"]
  gateways: ["$SYSTEM_NS/devspaces"]
  http:
    - name: tunnel
      match: [{ uri: { regex: "^/api/workspaces/[^/]+/tunnel$" } }]
      timeout: 0s
      retries: { attempts: 0 }
      route: [{ destination: { host: workspace-portal.$SYSTEM_NS.svc.cluster.local, port: { number: 80 } } }]
    - name: portal
      timeout: 120s
      route: [{ destination: { host: workspace-portal.$SYSTEM_NS.svc.cluster.local, port: { number: 80 } } }]
---
# 3. Let the gateway pods reach the portal pods.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: workspace-portal-from-route
  namespace: $SYSTEM_NS
  labels: { app.kubernetes.io/part-of: devspaces }
spec:
  podSelector: { matchLabels: { app.kubernetes.io/name: workspace-portal } }
  policyTypes: [Ingress]
  ingress:
    - from: [{ namespaceSelector: { matchLabels: { kubernetes.io/metadata.name: $gw_ns } } }]
      ports: [{ port: 8080, protocol: TCP }]
EOT
  if [ -n "$cidr_json" ]; then cat <<EOT
---
# 4. Door lock (AUTH=dev): on the gateway, requests for this host from anyone NOT in ALLOW_CIDRS are denied.
#    The gateway Service must keep client IPs (externalTrafficPolicy: Local) for this to see real addresses.
apiVersion: security.istio.io/v1
kind: AuthorizationPolicy
metadata:
  name: devspaces-allow-cidrs
  namespace: $gw_ns
  labels: { app.kubernetes.io/part-of: devspaces }
spec:
  selector: { matchLabels: { $sel } }
  action: DENY
  rules:
    - to: [{ operation: { hosts: ["$PORTAL_HOST", "$PORTAL_HOST:*"] } }]
      from: [{ source: { notRemoteIpBlocks: [$cidr_json] } }]
EOT
  fi
}

step "Route: EXPOSE=$EXPOSE → $SCHEME://$PORTAL_HOST"
case "$EXPOSE" in
  ingress) render_ingress | grep -v '^$' > "$OUT";;
  istio)   render_istio   | grep -v '^$' > "$OUT";;
  *) fail "EXPOSE must be port-forward, ingress or istio";;
esac
ok "wrote $OUT"; [ "$SHOW" = 1 ] && { cat "$OUT"; exit 0; }
run k apply -f "$OUT"
[ "$AUTH" = dev ] && warn "AUTH=dev: everyone in ALLOW_CIDRS ($cidr_list) acts as $DEV_USER — fine for a trial, switch to AUTH=oidc before inviting a team"

step "Where to point DNS"
ip=""
if [ "$DRY_RUN" != 1 ]; then
  if [ "$EXPOSE" = istio ]; then ip=$GW_IP; else
    ip=$(kq -n "$SYSTEM_NS" get ingress devspaces -o jsonpath='{.status.loadBalancer.ingress[0].ip}{.status.loadBalancer.ingress[0].hostname}')
    [ -z "$ip" ] && ip=$(kq get svc -A -l "app.kubernetes.io/name in (ingress-nginx, traefik)" -o jsonpath='{range .items[?(@.spec.type=="LoadBalancer")]}{.status.loadBalancer.ingress[0].ip}{.status.loadBalancer.ingress[0].hostname}{end}' | head -c 64)
  fi
fi
cat <<EOT
  A record:   $PORTAL_HOST  →  ${ip:-<the controller/gateway address: kubectl get svc -A | grep LoadBalancer>}
  Test now:   curl -s -H 'Host: $PORTAL_HOST' http://${ip:-<address>}/healthz      → ok
  Then open:  $SCHEME://$PORTAL_HOST        wsctl login --portal $SCHEME://$PORTAL_HOST$([ "$AUTH" = dev ] && echo " --dev")
EOT
[ -n "$TLS_SECRET" ] && echo "  TLS: Secret $TLS_SECRET must exist in $([ "$EXPOSE" = istio ] && echo "${GW_NS:-istio-system}" || echo "$SYSTEM_NS") (cert-manager: kubectl get certificate -A)"
echo; echo "Next:  ./50-developers.sh"
