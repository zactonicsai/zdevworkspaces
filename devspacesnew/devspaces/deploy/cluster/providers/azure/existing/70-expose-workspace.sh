#!/usr/bin/env bash
# 70 — Give a developer's running dev pod a web address through the existing Istio gateway.
# A workspace only has an SSH Service. If the developer runs a web app inside it (say `npm run
# dev` on port 3000), this adds three small objects in the developer's namespace:
#
#   Service        ws-<workspace>-web-<port>   → the pod, that port
#   NetworkPolicy  allow-gateway-<workspace>   → lets the gateway namespace reach that port
#                                                (developer namespaces only accept traffic from themselves)
#   VirtualService ws-<workspace>-<port>       → <workspace>-<developer>.<APPS_DOMAIN> on the Gateway from 60-
#
#   ./70-expose-workspace.sh <developer e-mail or short name> <workspace> <port> [--remove] [--dry-run]
#   e.g. ./70-expose-workspace.sh alice@corp.example web 3000     → http://web-alice.apps.workspaces.corp.example
#
# ALLOW_CIDRS (env.sh) adds the same IP door-lock as the portal route. Developers can run this
# themselves if they have RBAC for Services/NetworkPolicies/VirtualServices in their namespace.
. "$(dirname "$0")/_lib.sh" "$@"; need_detect
REMOVE=0; args=(); for _a in "$@"; do case "$_a" in --remove) REMOVE=1;; --dry-run) ;; *) args+=("$_a");; esac; done
[ "${#args[@]}" -ge 3 ] || { sed -n 2,17p "$0" | sed 's/^# \{0,1\}//'; exit 1; }
dev=${args[0]}; ws=${args[1]}; port=${args[2]}
short=$(printf '%s' "$dev" | cut -d@ -f1 | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9-]/-/g')
ns="ws-$short"
domain=${APPS_DOMAIN:-apps.${PORTAL_HOST:-example.com}}
host="$ws-$short.$domain"
gw_ns=${GW_NS:-istio-system}
gateway_ref="$SYSTEM_NS/devspaces"; [ -n "$EXISTING_GATEWAY" ] && gateway_ref=$EXISTING_GATEWAY
case "$port" in ''|*[!0-9]*) fail "port must be a number (got '$port')";; esac
OUT="$EX_DIR/route-$short-$ws-$port.yaml"

render() {
cat <<EOT
# generated by 70-expose-workspace.sh — $dev / workspace $ws / port $port → http://$host
apiVersion: v1
kind: Service
metadata:
  name: ws-$ws-web-$port
  namespace: $ns
  labels: { devspaces.io/workspace: "$ws", devspaces.io/exposed-port: "$port" }
spec:
  selector: { devspaces.io/workspace: "$ws" }     # the dev pod carries this label
  ports: [{ name: web, port: $port, targetPort: $port }]
---
# developer namespaces have a "same namespace only" ingress rule; open just this port to the gateway
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: allow-gateway-$ws-$port
  namespace: $ns
  labels: { devspaces.io/workspace: "$ws", devspaces.io/exposed-port: "$port" }
spec:
  podSelector: { matchLabels: { devspaces.io/workspace: "$ws" } }
  policyTypes: [Ingress]
  ingress:
    - from: [{ namespaceSelector: { matchLabels: { kubernetes.io/metadata.name: $gw_ns } } }]
      ports: [{ protocol: TCP, port: $port }]
---
# the route: this host name, on the gateway that 60-virtualservice.sh (or Helm) created, to the Service above
apiVersion: networking.istio.io/v1
kind: VirtualService
metadata:
  name: ws-$ws-$port
  namespace: $ns
  labels: { devspaces.io/workspace: "$ws", devspaces.io/exposed-port: "$port" }
spec:
  hosts: ["$host"]
  gateways: ["$gateway_ref"]
  http:
    - route:
        - destination:
            host: ws-$ws-web-$port.$ns.svc.cluster.local
            port: { number: $port }
      timeout: 0s                 # dev servers do live-reload over WebSockets; never cut them
      retries: { attempts: 0 }
EOT
if [ -n "$ALLOW_CIDRS" ]; then
cidrs=$(printf '%s' "$ALLOW_CIDRS" | tr ',' '\n' | sed 's/^ *//;s/ *$//' | grep -v '^$' | sed 's/.*/"&"/' | paste -sd, -)
sel_key=${GW_SELECTOR%%:*}; sel_val=$(printf '%s' "${GW_SELECTOR#*:}" | sed 's/^ *//')
cat <<EOT
---
apiVersion: security.istio.io/v1
kind: AuthorizationPolicy
metadata:
  name: ws-$short-$ws-$port-allow-cidrs
  namespace: $gw_ns
  labels: { devspaces.io/workspace: "$ws", devspaces.io/exposed-port: "$port" }
spec:
  selector: { matchLabels: { ${sel_key:-istio}: ${sel_val:-ingressgateway} } }
  action: DENY
  rules:
    - to: [{ operation: { hosts: ["$host", "$host:*"] } }]
      from: [{ source: { notRemoteIpBlocks: [$cidrs] } }]
EOT
fi
}

if [ "$REMOVE" = 1 ]; then
  step "Removing the route for $dev / $ws / $port"
  render > "$OUT"; run k delete -f "$OUT" --ignore-not-found; rm -f "$OUT"; ok "gone"; exit 0
fi

step "Exposing $dev / workspace '$ws' port $port as http://$host"
[ -n "$(kq -n "$ns" get statefulset "ws-$ws" -o name)" ] || [ "$DRY_RUN" = 1 ] || fail "no workspace '$ws' in $ns (create one first: wsctl create $ws --lang node, or the portal)"
hostok=$(kq -n "${gateway_ref%%/*}" get gateway "${gateway_ref##*/}" -o jsonpath='{.spec.servers[*].hosts[*]}')
if [ "$DRY_RUN" != 1 ] && [ -n "$hostok" ] && ! printf '%s\n' $hostok | grep -qE "^(\*|\*\.${domain}|${host}|\*/\*|\*\.\*)$"; then
  warn "Gateway $gateway_ref only lists hosts: $hostok — it will ignore $host."
  warn "add \"*.$domain\" to that Gateway's hosts (kubectl -n ${gateway_ref%%/*} edit gateway ${gateway_ref##*/}), then run again"
fi
render > "$OUT"; ok "wrote $OUT"
run k apply -f "$OUT"
cat <<EOT

  DNS:    *.$domain  →  ${GW_IP:-<gateway ip>}   (one wildcard A record covers every exposed workspace)
  Try:    curl -H 'Host: $host' http://${GW_IP:-<gateway ip>}/        (before DNS exists)
  Open:   http://$host
  Inside the dev pod the app must listen on 0.0.0.0:$port (not 127.0.0.1), e.g.  npm run dev -- --host 0.0.0.0 --port $port
  Remove: ./70-expose-workspace.sh $dev $ws $port --remove
EOT
