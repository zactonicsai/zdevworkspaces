#!/usr/bin/env bash
# 60 — "Istio is already set up: just add the route."
# Publishes the portal through the ingress gateway your cluster already has, by applying only
# Istio routing objects (no new load balancer, no new Istio install):
#
#   Gateway        "devspaces"  — opens PORTAL_HOST on the existing gateway pods (skipped when you
#                                 give EXISTING_GATEWAY=namespace/name)
#   VirtualService "devspaces"  — sends PORTAL_HOST to the portal Service (or to oauth2-proxy)
#   AuthorizationPolicy "devspaces-allow-cidrs" — optional door-lock: only ALLOW_CIDRS may use it
#
# AUTH=entra / AUTH=oidc: the Helm chart already created the Gateway + VirtualService, so this
# script only shows them and tests the route. AUTH=dev: the portal has NO login, so the route is
# refused unless ALLOW_CIDRS is set (or OPEN_DEV_PORTAL=yes, for a lab on a private network).
#
#   ./60-virtualservice.sh [--dry-run] [--show]    --show prints the YAML and exits
# Everything it applies is also written to route-portal.yaml next to this script.
. "$(dirname "$0")/_lib.sh" "$@"; need_detect
SHOW=0; for _a in "$@"; do [ "$_a" = --show ] && SHOW=1; done
OUT="$EX_DIR/route-portal.yaml"
[ -n "$GW_SELECTOR" ] || [ "$DRY_RUN" = 1 ] || fail "00-detect.sh found no Istio ingress gateway on this cluster (GW_SELECTOR empty). Install/enable one first: az aks mesh enable-ingress-gateway --ingress-gateway-type external"
[ -n "$PORTAL_HOST" ] || fail "set PORTAL_HOST in env.sh (the DNS name people will type)"
gw_ns=${GW_NS:-istio-system}
scheme=http; [ -n "$TLS_CREDENTIAL_NAME" ] && scheme=https
backend=workspace-portal; [ "$AUTH" = entra ] && backend=oauth2-proxy
gateway_ref="$SYSTEM_NS/devspaces"; [ -n "$EXISTING_GATEWAY" ] && gateway_ref=$EXISTING_GATEWAY
apps_domain=${APPS_DOMAIN:-apps.$PORTAL_HOST}

# ---- AUTH=dev safety: a portal that trusts everyone must not be reachable by everyone
if [ "$AUTH" = dev ] && [ -z "$ALLOW_CIDRS" ] && [ "${OPEN_DEV_PORTAL:-no}" != yes ]; then
  fail "AUTH=dev + gateway = a portal with no login on the internet. Set ALLOW_CIDRS=\"<your ip>/32\" in env.sh (curl -s https://ifconfig.me) — or AUTH=entra/oidc — and run again."
fi

render() {
cat <<EOT
# generated by deploy/cluster/providers/azure/existing/60-virtualservice.sh — safe to edit and kubectl apply again
EOT
if [ -z "$EXISTING_GATEWAY" ]; then
cat <<EOT
# 1. The Gateway: "on the gateway pods that already exist (selector), listen for this host name".
apiVersion: networking.istio.io/v1
kind: Gateway
metadata:
  name: devspaces
  namespace: $SYSTEM_NS
spec:
  selector:
    ${GW_SELECTOR:-istio: ingressgateway}
  servers:
    - port: { number: 80, name: http, protocol: HTTP }
      hosts: ["$PORTAL_HOST", "*.$apps_domain"]     # the portal, and developers' apps (70-expose-workspace.sh)
EOT
[ -n "$TLS_CREDENTIAL_NAME" ] && cat <<EOT
      tls: { httpsRedirect: true }
    - port: { number: 443, name: https, protocol: HTTPS }
      hosts: ["$PORTAL_HOST", "*.$apps_domain"]
      tls:
        mode: SIMPLE
        credentialName: $TLS_CREDENTIAL_NAME     # TLS Secret in namespace $gw_ns
EOT
echo "---"
fi
cat <<EOT
# 2. The VirtualService: "requests for this host go to this Service". The SSH tunnel path is a
#    WebSocket that stays open for hours, so it gets no timeout and no retries.
apiVersion: networking.istio.io/v1
kind: VirtualService
metadata:
  name: devspaces
  namespace: $SYSTEM_NS
spec:
  hosts: ["$PORTAL_HOST"]
  gateways: ["$gateway_ref"]
  http:
    - name: tunnel
      match: [{ uri: { regex: "^/api/workspaces/[^/]+/tunnel$" } }]
      timeout: 0s
      retries: { attempts: 0 }
      route:
        - destination:
            host: $backend.$SYSTEM_NS.svc.cluster.local
            port: { number: 80 }
    - name: portal
      timeout: 120s
      route:
        - destination:
            host: $backend.$SYSTEM_NS.svc.cluster.local
            port: { number: 80 }
EOT
if [ -n "$ALLOW_CIDRS" ]; then
cidrs=$(printf '%s' "$ALLOW_CIDRS" | tr ',' '\n' | sed 's/^ *//;s/ *$//' | grep -v '^$' | sed 's/.*/"&"/' | paste -sd, -)
sel_key=${GW_SELECTOR%%:*}; sel_val=$(printf '%s' "${GW_SELECTOR#*:}" | sed 's/^ *//')
cat <<EOT
---
# 3. The door lock: on the gateway pods, requests for $PORTAL_HOST are allowed only from these
#    client IPs (needs the gateway Service with externalTrafficPolicy: Local, which the AKS add-on
#    uses, or X-Forwarded-For from a trusted front door — see the tutorial).
apiVersion: security.istio.io/v1
kind: AuthorizationPolicy
metadata:
  name: devspaces-allow-cidrs
  namespace: $gw_ns
spec:
  selector:
    matchLabels: { ${sel_key:-istio}: ${sel_val:-ingressgateway} }
  action: DENY
  rules:
    - to: [{ operation: { hosts: ["$PORTAL_HOST", "$PORTAL_HOST:*"] } }]
      from: [{ source: { notRemoteIpBlocks: [$cidrs] } }]
EOT
fi
}

step "Portal route on the existing Istio gateway ($gw_ns, ${GW_SELECTOR:-?}) for $scheme://$PORTAL_HOST"
render > "$OUT"; ok "wrote $OUT"
if [ "$SHOW" = 1 ]; then cat "$OUT"; exit 0; fi

if [ "$AUTH" = entra ] || [ "$AUTH" = oidc ]; then
  if [ -n "$(kq -n "$SYSTEM_NS" get virtualservice devspaces -o name)" ]; then
    skip "Helm already manages Gateway+VirtualService 'devspaces' in $AUTH mode — not re-applying (edit values-existing.yaml instead)"
    [ -n "$ALLOW_CIDRS" ] && { python3 - "$OUT" <<'PY' | run k apply -f -
import sys; docs=open(sys.argv[1]).read().split("\n---\n"); print("\n---\n".join(d for d in docs if "kind: AuthorizationPolicy" in d))
PY
      ok "applied the ALLOW_CIDRS door lock only"; }
  else
    run k apply -f "$OUT"; ok "applied (Helm had ingress.enabled=false, so these objects are yours to keep)"
  fi
else
  run k apply -f "$OUT"; ok "applied: Gateway$([ -n "$EXISTING_GATEWAY" ] && echo " (reused $EXISTING_GATEWAY)"), VirtualService$([ -n "$ALLOW_CIDRS" ] && echo ", AuthorizationPolicy for $ALLOW_CIDRS")"
  warn "AUTH=dev: everyone who can reach $PORTAL_HOST is '$DEV_USER'. Keep ALLOW_CIDRS tight; switch to AUTH=entra/oidc before inviting a team."
fi

if [ -n "$ALLOW_CIDRS" ] && [ "$DRY_RUN" != 1 ]; then
  # the lock compares the *client* IP: the gateway Service must keep it (externalTrafficPolicy: Local)
  gsvc=$(kq -n "$gw_ns" get svc -l "${GW_SELECTOR%%:*}=$(printf '%s' "${GW_SELECTOR#*:}" | sed 's/^ *//')" -o jsonpath='{.items[0].metadata.name}')
  etp=$(kq -n "$gw_ns" get svc "$gsvc" -o jsonpath='{.spec.externalTrafficPolicy}')
  if [ -n "$gsvc" ] && [ "$etp" != Local ]; then
    warn "gateway Service $gw_ns/$gsvc has externalTrafficPolicy=$etp: the client IP is hidden behind the node, so ALLOW_CIDRS would block everyone."
    warn "fix: kubectl --context $KCTX -n $gw_ns patch svc $gsvc -p '{\"spec\":{\"externalTrafficPolicy\":\"Local\"}}'   (the add-on keeps this setting)"
  else
    ok "gateway Service ${gsvc:-?} keeps client IPs (externalTrafficPolicy=Local) — the ALLOW_CIDRS lock will work"
  fi
fi

step "Checking the route"
if [ "$DRY_RUN" = 1 ]; then skip "dry-run"; else
  k -n "$SYSTEM_NS" get gateway,virtualservice 2>/dev/null || true
  if [ -n "$GW_IP" ] && have curl; then
    code=$(curl -s -o /dev/null -m 10 -w '%{http_code}' -H "Host: $PORTAL_HOST" "http://$GW_IP/healthz" || echo 000)
    case "$code" in
      200) ok "http://$GW_IP/healthz with Host: $PORTAL_HOST → 200 — the gateway reaches the portal";;
      403) warn "403 from the gateway: your IP is not in ALLOW_CIDRS (or an AuthorizationPolicy/RequestAuthentication blocks it)";;
      404) warn "404: the gateway got the request but no route matched — Host name or Gateway selector mismatch (kubectl -n $gw_ns get gateway -A)";;
      000) warn "no answer from $GW_IP — is the gateway Service external, and does an NSG allow port 80?";;
      *)   warn "got HTTP $code";;
    esac
  else
    skip "no gateway IP / curl to test with"
  fi
fi
cat <<EOT

  DNS:   create an A record   $PORTAL_HOST  →  ${GW_IP:-<gateway ip>}      (or test now: curl -H 'Host: $PORTAL_HOST' http://${GW_IP:-<gateway ip>}/)
  Open:  $scheme://$PORTAL_HOST
  wsctl: wsctl login --portal $scheme://$PORTAL_HOST$([ "$AUTH" = dev ] && echo " --dev")
Next:  ./40-dev-pods.sh (spin up developer pods)   ·   ./70-expose-workspace.sh <developer> <workspace> <port>
EOT
