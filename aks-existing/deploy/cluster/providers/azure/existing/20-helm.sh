#!/usr/bin/env bash
# 2/5 — Install the Kubernetes layer with Helm: catalog, RBAC, admission policies, reaper,
# the portal (workspaces + tools), and either oauth2-proxy + Istio gateway (AUTH=entra) or a
# port-forward-only trial portal (AUTH=dev). Writes values-existing.yaml next to this script so
# you can see — and version — exactly what was installed. Re-run to upgrade.
#   ./20-helm.sh [--dry-run]
. "$(dirname "$0")/_lib.sh" "$@"; need_detect
have helm || [ "$DRY_RUN" = 1 ] || fail "helm not found"
VALUES="$EX_DIR/values-existing.yaml"

step "Writing $VALUES (AUTH=$AUTH, mesh=$MESH)"
mesh_mode=$MESH; [ "$mesh_mode" = none ] && mesh_mode=none
shared_choice=""
[ -n "$SHARED" ] && shared_choice="    - { name: shared, label: Shared folder, kind: shared, storageClass: $SHARED, accessModes: [ReadWriteMany], default: true,
        description: \"Azure Files share: mount in several workspaces at once and share with teammates (/shared/<name>).\" }"
cat > "$VALUES" <<EOT
# generated by deploy/cluster/providers/azure/existing/20-helm.sh — edit and re-run, or keep in git
global:
  registry: $REGISTRY
  tag: "$TAG"
  pullSecretName: ${PULL_SECRET_DOCKERCONFIG:+registry-pull}
pullSecret:
  dockerconfigjson: "${PULL_SECRET_DOCKERCONFIG}"
catalogOverrides:
  artifactory:
    url: "${ARTIFACTORY_URL}"
  defaults: { idleTimeout: ${WORKSPACE_IDLE:-4h} }
storage:
  choices:
    - { name: fast, label: Fast SSD, kind: home, storageClass: $HOME_FAST, accessModes: [ReadWriteOnce], default: true,
        description: "Premium SSD managed disk. Kept when the workspace is deleted." }
    - { name: standard, label: Standard, kind: home, storageClass: $HOME_STD, accessModes: [ReadWriteOnce],
        description: "Standard SSD managed disk. Cheaper; same persistence rules." }
$shared_choice
  snapshotClass: "$SNAP_CLASS"
  protectHomeDrives: true
networking:
  mesh: $mesh_mode
  istioRevision: "$ISTIO_REV"
  links: true
multicast:
  mode: none                      # existing cluster: no Multus / BYO-Cilium assumptions; enable later if you need it
runtimeClasses:
  gvisor: { enabled: false }
  kata:   { enabled: false }
devicePlugins:
  smarterDeviceManager: { enabled: false }
admission:
  enabled: true
reaper:
  enabled: true
portal:
  enabled: true
  replicas: ${PORTAL_REPLICAS:-1}
  trustedProxies: "${POD_CIDR:-10.244.0.0/16},10.0.0.0/8"
  sharing: true
EOT
if [ "$AUTH" = entra ]; then
  [ -n "$ENTRA_TENANT_ID" ] && [ -n "$ENTRA_PORTAL_CLIENT_ID" ] && [ -n "$ENTRA_PORTAL_CLIENT_SECRET" ] || [ "$DRY_RUN" = 1 ] || fail "AUTH=entra needs ENTRA_TENANT_ID, ENTRA_PORTAL_CLIENT_ID, ENTRA_PORTAL_CLIENT_SECRET (run ../30-entra.sh)"
  cookie=$(python3 -c 'import os,base64;print(base64.urlsafe_b64encode(os.urandom(32)).decode())')
  cat >> "$VALUES" <<EOT
  oidc:
    issuer: https://login.microsoftonline.com/${ENTRA_TENANT_ID:-TENANT}/v2.0
    audience: ${API_AUDIENCE}
    userClaim: preferred_username
    groupsClaim: groups
  cliLogin:
    tenant: "${ENTRA_TENANT_ID}"
    clientId: "${ENTRA_CLI_CLIENT_ID}"
    scope: "${API_AUDIENCE}/Workspaces.ReadWrite"
oauth2Proxy:
  enabled: true
  provider: entra-id
  issuerUrl: https://login.microsoftonline.com/${ENTRA_TENANT_ID:-TENANT}/v2.0
  emailDomain: "*"
  clientId: "${ENTRA_PORTAL_CLIENT_ID}"
  clientSecret: "${ENTRA_PORTAL_CLIENT_SECRET}"
  cookieSecret: "${cookie}"
  extraArgs: ["--oidc-groups-claim=groups", "--scope=openid profile email", "--cookie-samesite=lax"]
ingress:
  enabled: $([ -n "$GW_SELECTOR" ] && echo true || echo false)
  host: ${PORTAL_HOST}
  istio:
    enabled: true
    gatewaySelector: { ${GW_SELECTOR:-istio: ingressgateway} }
    credentialName: "${TLS_CREDENTIAL_NAME}"
    httpsRedirect: $([ -n "$TLS_CREDENTIAL_NAME" ] && echo true || echo false)
istioAuth:
  enabled: $([ "$MESH" != none ] && echo true || echo false)
  strictMTLS: true
  jwt:
    enabled: true
    issuer: https://login.microsoftonline.com/${ENTRA_TENANT_ID:-TENANT}/v2.0
    jwksUri: https://login.microsoftonline.com/${ENTRA_TENANT_ID:-TENANT}/discovery/v2.0/keys
    audiences: ["${API_AUDIENCE}"]
networkPolicy:
  enabled: true
EOT
  ok "Entra ID sign-in through the Istio gateway (${GW_IP:-<gateway ip>} ← ${PORTAL_HOST})"
else
  cat >> "$VALUES" <<EOT
  devUser: "${DEV_USER}"          # trial mode: every call runs as this identity; the Service is ClusterIP only
oauth2Proxy:
  enabled: false
ingress:
  enabled: false                  # reach it with: kubectl -n $SYSTEM_NS port-forward svc/workspace-portal 8080:80
istioAuth:
  enabled: $([ "$MESH" != none ] && echo true || echo false)
  strictMTLS: true
  jwt: { enabled: false }
networkPolicy:
  enabled: false                  # no auth proxy to pin the portal to; port-forward goes through the API server
EOT
  warn "AUTH=dev: the portal trusts everyone as $DEV_USER and is NOT exposed. Fine for a trial; switch to AUTH=entra before sharing the URL."
fi
ok "$VALUES"

step "helm upgrade --install $RELEASE ($CHART)"
run helm upgrade --install "$RELEASE" "$CHART" --kube-context "$KCTX" -n "$SYSTEM_NS" -f "$VALUES" --wait --timeout 10m
if [ "$DRY_RUN" != 1 ]; then
  k -n "$SYSTEM_NS" rollout status deploy/workspace-portal --timeout=180s
  ok "portal running: $(k -n "$SYSTEM_NS" get pods -l app.kubernetes.io/name=workspace-portal -o jsonpath='{.items[*].status.phase}')"
fi
echo
if [ "$AUTH" = entra ]; then
  echo "  Point DNS ${PORTAL_HOST} → ${GW_IP:-<gateway ip from 00-detect>} then open https://${PORTAL_HOST}"
else
  echo "  kubectl --context $KCTX -n $SYSTEM_NS port-forward svc/workspace-portal 8080:80   →  http://localhost:8080"
fi
echo "Next:  ./30-istio-check.sh (optional)   ./40-dev-pods.sh"
