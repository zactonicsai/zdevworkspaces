package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"strings"
)

// uiConfig is what /config.js hands the browser: where the API is, how to sign in, and
// whether to use stub data. The same UI build therefore works behind oauth2-proxy (session
// mode), with a Keycloak/Entra PKCE login (oidc.issuer set), against an API on another
// host (apiBase), or with no API at all (stub).
type uiConfig struct {
	APIBase         string `json:"apiBase"`
	OIDC            uiOIDC `json:"oidc"`
	Stub            bool   `json:"stub"`
	AllowStubToggle bool   `json:"allowStubToggle"`
}

type uiOIDC struct {
	Issuer   string `json:"issuer"`
	ClientID string `json:"clientId"`
	Scope    string `json:"scope"`
	Audience string `json:"audience"`
}

func (c uiConfig) js() []byte {
	b, _ := json.MarshalIndent(c, "", "  ")
	return []byte("/* generated by the portal from its -ui-* flags */\nwindow.PORTAL_CONFIG = " + string(b) + ";\n")
}

func (c uiConfig) handler() http.Handler {
	body := c.js()
	return http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/javascript; charset=utf-8")
		w.Header().Set("Cache-Control", "no-store")
		_, _ = w.Write(body)
	})
}

// cspFor widens connect-src for a remote API and the OIDC issuer (token endpoint is called
// from the browser), leaving everything else as strict as defaultCSP.
func cspFor(base string, c uiConfig) string {
	extra := []string{}
	for _, u := range []string{c.APIBase, c.OIDC.Issuer} {
		if o := originOf(u); o != "" {
			extra = append(extra, o)
		}
	}
	if len(extra) == 0 || base == "" {
		return base
	}
	return strings.Replace(base, "connect-src 'self'", "connect-src 'self' "+strings.Join(extra, " "), 1)
}

func originOf(raw string) string {
	u, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || u.Scheme == "" || u.Host == "" {
		return ""
	}
	return u.Scheme + "://" + u.Host
}

// cors allows a UI served from another origin (e.g. a CDN or a separate static bucket) to call
// the API with a bearer token. Origins are an explicit allow-list; credentials are allowed so
// session cookies work too when the proxy sits in front of both.
func cors(allowed []string, next http.Handler) http.Handler {
	set := map[string]bool{}
	for _, o := range allowed {
		if o = strings.TrimSpace(o); o != "" {
			set[o] = true
		}
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		origin := r.Header.Get("Origin")
		if origin != "" && (set[origin] || set["*"]) {
			h := w.Header()
			h.Set("Access-Control-Allow-Origin", origin)
			h.Set("Access-Control-Allow-Credentials", "true")
			h.Set("Vary", "Origin")
			if r.Method == http.MethodOptions {
				h.Set("Access-Control-Allow-Methods", "GET, POST, PUT, DELETE, OPTIONS")
				h.Set("Access-Control-Allow-Headers", "Authorization, Content-Type, X-Requested-With")
				h.Set("Access-Control-Max-Age", fmt.Sprint(600))
				w.WriteHeader(http.StatusNoContent)
				return
			}
		}
		next.ServeHTTP(w, r)
	})
}
